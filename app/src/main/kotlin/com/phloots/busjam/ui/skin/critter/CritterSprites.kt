package com.phloots.busjam.ui.skin.critter

import android.annotation.SuppressLint
import android.content.Context
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.FilterQuality
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.res.imageResource
import androidx.compose.ui.unit.IntOffset
import androidx.compose.ui.unit.IntSize
import kotlin.math.roundToInt

/**
 * The chibi critter sprites (sitting, front and right-facing): one per [Species] and palette colour, named
 * `critter_<species>_<colour>_<view>`. Generated by art/tools/critter_sprites.py.
 */
object CritterSprites {
    private var front: Map<Species, List<ImageBitmap>> = emptyMap()
    private var right: Map<Species, List<ImageBitmap>> = emptyMap()

    /** Decodes the sprites once; later calls do nothing. */
    @SuppressLint("DiscouragedApi") // 80 sprites named by species and colour; looked up once
    fun load(context: Context) {
        if (front.isNotEmpty()) return
        val res = context.resources
        fun set(view: String) = Species.entries.associateWith { species ->
            CritterPalette.names.map { colour ->
                val id = res.getIdentifier("critter_${species.name.lowercase()}_${colour}_$view", "drawable", context.packageName)
                ImageBitmap.imageResource(res, id)
            }
        }
        front = set("front")
        right = set("right")
    }

    /** Width over height of the [species]' front view. */
    fun frontAspect(species: Species): Float =
        front[species]?.firstOrNull()?.let { it.width.toFloat() / it.height } ?: 0.64f

    /**
     * Draws the [species] critter in palette colour [color] with its bottom centre at [base], [height] tall, facing
     * the viewer or, when [walking], to the right. Draws nothing before [load].
     */
    fun DrawScope.drawCritter(base: Offset, height: Float, species: Species, color: Int, walking: Boolean, alpha: Float) {
        val set = (if (walking) right else front)[species]
        if (set.isNullOrEmpty() || alpha <= 0f) return
        val img = set[color.mod(set.size)]
        val w = height * img.width / img.height
        drawImage(
            img,
            dstOffset = IntOffset((base.x - w / 2).roundToInt(), (base.y - height).roundToInt()),
            dstSize = IntSize(w.roundToInt(), height.roundToInt()),
            alpha = alpha,
            filterQuality = FilterQuality.High,
        )
    }
}
