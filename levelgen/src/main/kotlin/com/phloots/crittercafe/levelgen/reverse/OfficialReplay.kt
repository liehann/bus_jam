package com.phloots.crittercafe.levelgen.reverse

import com.phloots.crittercafe.core.generator.reverse.Quality
import com.phloots.crittercafe.core.generator.reverse.Readability
import com.phloots.crittercafe.core.generator.reverse.StallDirector
import com.phloots.crittercafe.core.io.LevelPackCodec
import com.phloots.crittercafe.core.model.Level
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import java.io.File
import java.util.concurrent.Executors

/**
 * Rebuilds a campaign level from its provenance record alone ([Provenance], keyed by the level's hash): the slot's
 * recipe from [plan], the director seed and try index, the belt (`queuePreview`), the construction (`clued`, or
 * `readable` in records written before the rename; [constructionOf]), the shrink to the slot's ring ([shrink]) and,
 * when `repairedElements` > 0, the queue repair ([Readability.repair]) — the steps [select5v] took. Null when the
 * try does not build. The tutorial (slot 1) is not generated by a recipe and is not replayed.
 */
internal fun replay(slotNumber: Int, meta: JsonObject): Level? {
    val slot = plan().first { it.number == slotNumber }
    val r = recipes4()[slot.recipe]
    val t = meta["try"]!!.jsonPrimitive.int
    val dseed = meta["directorSeed"]!!.jsonPrimitive.long
    val base = r.build(t)
    val belt = meta["queuePreview"]?.jsonPrimitive?.int ?: base.queuePreview
    val sl = StallDirector(base.copy(queuePreview = belt, clued = cluedDef(constructionOf(meta), slot.ring, belt)), dseed).run() ?: return null
    var (lv, line) = shrink(sl.level, slot.ring, sl.line)
    if ((meta["repairedElements"]?.jsonPrimitive?.int ?: 0) > 0) lv = Readability.repair(lv, line, Quality.measure(lv, line).states).level
    return lv.copy(id = slotNumber)
}

/**
 * Determinism check of a shipped campaign: every level of --pack (default app/src/main/assets/levels.json) is rebuilt
 * from its record in --meta (default levelgen/out/official-meta.json) with [replay] and compared with the shipped
 * level (equal [Level] and equal hash). Preview packs (whose
 * records carry `slot`) work too. Prints one line per slot and exits non-zero on any mismatch.
 * Run: ./gradlew :levelgen:reversePreview -PreverseMain=com.phloots.crittercafe.levelgen.reverse.OfficialReplayKt
 *      [--args="--pack levelgen/out/clued-rebuild-levels.json --meta levelgen/out/clued-rebuild-meta.json --threads 6 --only 37,52"]
 */
fun main(args: Array<String>) {
    val opts = HashMap<String, String>()
    var i = 0
    while (i + 1 < args.size) { opts[args[i].removePrefix("--")] = args[i + 1]; i += 2 }
    val pack = LevelPackCodec.decode(File(opts["pack"] ?: "app/src/main/assets/levels.json").readText()).levels.map { it.level }
    val meta = Provenance.read(File(opts["meta"] ?: "levelgen/out/official-meta.json"))
    val threads = opts["threads"]?.toInt() ?: 4
    val only = opts["only"]?.split(",")?.map { it.trim().toInt() }?.toSet()
    val exec = Executors.newFixedThreadPool(threads)
    val jobs = pack.filter { only == null || it.id in only }.map { lv ->
        lv.id to exec.submit<String> {
            val h = Provenance.hash(lv)
            val m = meta[h] ?: return@submit "MISSING no provenance record for $h"
            if (m["recipe"]?.jsonPrimitive?.content == "tutorial") return@submit "ok $h (tutorial, not replayed)"
            // preview packs number their levels 1..n and record the slot
            val slot = m["slot"]?.jsonPrimitive?.int ?: lv.id
            val again = replay(slot, m)?.copy(id = lv.id) ?: return@submit "FAILED try does not build"
            if (again == lv && Provenance.hash(again) == h) "ok $h (${constructionOf(m)})" else "DIFFERS ${Provenance.hash(again)} vs $h"
        }
    }
    var bad = 0
    for ((id, f) in jobs) {
        val res = f.get()
        if (!res.startsWith("ok")) bad++
        println("L$id $res")
    }
    exec.shutdown()
    println("replayed ${jobs.size} levels: ${jobs.size - bad} identical, $bad not")
    if (bad > 0) kotlin.system.exitProcess(1)
}
